// The three files Connect owns beside Cursor: the hook program Cursor runs for
// every hook event, its launcher, and the launcher the collector service starts.
// All three are generated text, so the package ships no loose executable and the
// capture choices are a constant inside the program, not a file it could fail to
// read. The program runs inside the editor's hot path: it is bounded, makes no
// network call and can only exit 0.

import fs from "node:fs";
import path from "node:path";
import type { ContentPolicy } from "../import/model.ts";
import { CREDENTIAL_BLOCK_RE, SECRET_ARGUMENT_RE, STRICT_ASSIGNMENT_RE, STRICT_CREDENTIAL_RE } from "../collector/scrub.ts";
import {
  CURSOR_FILE_MARKER, CURSOR_NODE_MAJOR, cursorShareFiles, cursorStateFiles, isSafeCursorPath, writeCursorFileAtomic,
  type CursorIdentity, type CursorNetwork, type CursorNode, type CursorPolicy,
} from "./config.ts";

/** Every event Connect registers. The first four are uploaded; the last two
 *  only give the collector context (models of a turn, sandbox flag). */
export const CURSOR_HOOK_EVENTS = [
  "beforeSubmitPrompt", "postToolUse", "postToolUseFailure", "stop", "afterAgentThought", "afterShellExecution",
] as const;
export type CursorHookEvent = (typeof CURSOR_HOOK_EVENTS)[number];

export const CURSOR_HOOK_LIMITS = Object.freeze({
  /** Hard bound on one invocation, well inside the 5 second hook timeout. */
  deadlineMs: 1500,
  stdinBytes: 4 * 1024 * 1024,
  /** One spool line, and so one O_APPEND write. */
  lineBytes: 32 * 1024,
  /** One segment file. A bucket that fills its segment continues in a numbered one. */
  segmentBytes: 1024 * 1024,
  /** Every segment together. Past this an event is dropped and counted. */
  spoolBytes: 128 * 1024 * 1024,
  /** Files in the spool: one per ten-minute bucket of the fourteen days a
   *  record is kept, the numbered ones of busy buckets, and room to spare. */
  segments: 2304,
  /** Width of the wall-clock bucket that names a segment. */
  segmentMs: 600_000,
  droppedBytes: 1024 * 1024,
  promptChars: 16 * 1024,
  /** Prefix of a prompt the credential patterns run over; bounds their cost. */
  scrubChars: 20 * 1024,
  inputChars: 1024,
});

/** One spool line, as the hook writes it and the collector reads it. */
export type CursorSpoolLine = {
  v: 1;
  /** 32 lowercase hex characters, minted per invocation. */
  id: string;
  /** Capture time in nanoseconds since the epoch as a decimal string. */
  t: string;
  hook: CursorHookEvent;
  conversation_id: string;
  /** The capture options that were on when the line was written. */
  p: CursorPolicy;
  payload: Record<string, unknown>;
};

/** A JavaScript literal for generated source, in ASCII whatever the value holds. */
const literal = (value: unknown): string =>
  JSON.stringify(value).replace(/[^\x20-\x7e]/g, char => `\\u${char.charCodeAt(0).toString(16).padStart(4, "0")}`);

/** The hook program: dependency-free CommonJS in syntax every Node.js release
 *  parses, because the launcher may fall back to whichever `node` is on PATH. */
export function cursorHookProgram(opts: { stateDir: string; content: ContentPolicy; identity: CursorIdentity }): string {
  if (!path.isAbsolute(opts.stateDir)) throw new Error("Cursor hook state directory must be absolute");
  const policy: CursorPolicy = {
    prompts: opts.content.prompts === true,
    toolDetails: opts.content.toolDetails === true,
    email: opts.identity.email === true,
  };
  return String.raw`"use strict";
// ${CURSOR_FILE_MARKER}
// Generated by codetelemetry-connect; "login --client cursor" rewrites this file.
// Cursor runs it once per hook event. It reads the event from stdin, keeps the
// allow-listed fields, appends one line to the local spool and exits 0. It makes
// no network call, starts no process and prints nothing.
var STATE = ${literal(opts.stateDir)};
var POLICY = ${literal(policy)};
var LIMITS = ${literal(CURSOR_HOOK_LIMITS)};
var HOOKS = ${literal(CURSOR_HOOK_EVENTS)};
var IDENTITY = /^[A-Za-z0-9][A-Za-z0-9._:-]{0,255}$/;
var EMAIL = /^[^\s@]{1,64}@[^\s@]{1,190}$/;
// Tool arguments kept under the tool-details option, by tool and value type.
var TOOL_INPUT = {
  Shell: { command: "string", cwd: "string", timeout: "number" },
  Read: { file_path: "string" },
  Write: { file_path: "string" },
  Grep: { pattern: "string", glob: "string", file_path: "string", output_mode: "string" },
  Task: { subagent_type: "string", run_in_background: "boolean", model: "string" }
};
var KEY = /cot_[A-Za-z0-9_-]{12,}/g;
// The strict credential patterns of the shared scrubber, applied in its order.
// They are best effort: a secret in a shape they do not name passes.
var BLOCK = new RegExp(${literal(CREDENTIAL_BLOCK_RE.source)}, "gi");
var CREDENTIAL = new RegExp(${literal(STRICT_CREDENTIAL_RE.source)}, "gi");
var ASSIGNMENT = new RegExp(${literal(STRICT_ASSIGNMENT_RE.source)}, "gi");
// A command line that passes a secret as an argument is withheld whole.
var ARGUMENT = new RegExp(${literal(SECRET_ARGUMENT_RE.source)}, "i");
var fs, crypto, captured;
var chunks = [], size = 0, over = false, settled = false, done = false;

function quit() {
  done = true;
  try { process.exit(0); } catch (error) {}
}
// One byte per event that produced no spool line; the collector reports the count.
function drop() {
  try {
    var fd = fs.openSync(STATE + "/dropped", appendFlags(), 384);
    try {
      if (fs.fstatSync(fd).size < LIMITS.droppedBytes) fs.writeSync(fd, ".");
    } finally { fs.closeSync(fd); }
  } catch (error) {}
}
function fail() {
  if (!done) drop();
  quit();
}
// Never through a link, and never waiting on a FIFO someone put in its place.
function appendFlags() {
  var c = fs.constants;
  return c.O_WRONLY | c.O_APPEND | c.O_CREAT | (c.O_NOFOLLOW || 0) | (c.O_NONBLOCK || 0);
}
// Microsecond wall-clock time as nanoseconds. No Cursor payload carries a time.
function stamp() {
  try {
    var clock = typeof performance === "object" && performance ? performance : require("perf_hooks").performance;
    var micros = Math.round(clock.timeOrigin * 1000) + Math.round(clock.now() * 1000);
    if (micros > 0 && micros <= 9007199254740991) return String(micros) + "000";
  } catch (error) {}
  return String(Date.now()) + "000000";
}
function isObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}
function isNumber(value) {
  return typeof value === "number" && isFinite(value);
}
function isInteger(value) {
  return isNumber(value) && Math.floor(value) === value && Math.abs(value) <= 9007199254740991;
}
function own(value, key) {
  return Object.prototype.hasOwnProperty.call(value, key);
}
function text(out, key, value, max) {
  if (typeof value === "string" && value.length > 0 && value.length <= max) out[key] = value;
}
function scrub(value) {
  return value.replace(KEY, function (match) { return "cot_\u2026" + match.slice(-4); })
    .replace(BLOCK, "<REDACTED>").replace(CREDENTIAL, "<REDACTED>").replace(ASSIGNMENT, "$1<REDACTED>");
}
function unchanged(value) {
  return scrub(value) === value && !/<REDACTED>|cot_\u2026/.test(value);
}
// The patterns run over a bounded prefix. A token cut by that bound is removed
// whole, so no part of a secret that straddles it can pass unmatched.
function promptText(value) {
  var end = value.length;
  if (end > LIMITS.scrubChars) {
    end = LIMITS.scrubChars;
    while (end > 0 && !/\s/.test(value.charAt(end - 1))) end--;
  }
  return whole(scrub(value.slice(0, end)).slice(0, LIMITS.promptChars));
}
// A cut never leaves half a character.
function whole(value) {
  var last = value.charCodeAt(value.length - 1);
  return last >= 0xd800 && last <= 0xdbff ? value.slice(0, -1) : value;
}
// A tool's arguments are kept whole or not at all: never cut, never redacted.
function toolInput(name, raw) {
  if (!POLICY.toolDetails || typeof name !== "string" || !own(TOOL_INPUT, name) || !isObject(raw)) return undefined;
  var allowed = TOOL_INPUT[name], out = {}, key, value;
  for (key in allowed) {
    if (!own(allowed, key) || !own(raw, key)) continue;
    value = raw[key];
    if (typeof value === allowed[key] && (typeof value !== "number" || isFinite(value))) out[key] = value;
  }
  if (name === "Task" && POLICY.prompts && typeof raw.description === "string") out.description = raw.description;
  var keys = Object.keys(out);
  if (!keys.length || JSON.stringify(out).length > LIMITS.inputChars) return undefined;
  for (var i = 0; i < keys.length; i++) {
    if (typeof out[keys[i]] === "string" && !unchanged(out[keys[i]])) return undefined;
  }
  if (name === "Shell" && typeof out.command === "string" && ARGUMENT.test(out.command)) return undefined;
  return out;
}
// Scalars derived from a tool's output before the output itself is dropped.
function toolResult(raw) {
  var out = {}, parsed = raw;
  if (typeof raw === "string") {
    try { parsed = JSON.parse(raw); } catch (error) { return out; }
  }
  if (!isObject(parsed)) return out;
  if (isInteger(parsed.exitCode)) out.exit_code = parsed.exitCode;
  if (typeof parsed.output === "string") out.output_bytes = Buffer.byteLength(parsed.output, "utf8");
  if (isInteger(parsed.content_length)) out.content_length = parsed.content_length;
  if (typeof parsed.success === "boolean") out.success = parsed.success;
  text(out, "agent_id", parsed.agentId, 256);
  return out;
}
function modelParams(raw) {
  if (!Array.isArray(raw)) return undefined;
  var out = [];
  for (var i = 0; i < raw.length && i < 32 && out.length < 8; i++) {
    var pair = {};
    if (!isObject(raw[i])) continue;
    text(pair, "id", raw[i].id, 64);
    text(pair, "value", raw[i].value, 64);
    if (own(pair, "id") && own(pair, "value")) out.push(pair);
  }
  return out.length ? out : undefined;
}
// The allow-list. A field is copied only by name, with its type and size
// checked; everything else in the event stays in this process.
function build(hook, input) {
  var out = {}, i, key, value;
  if (hook === "afterShellExecution") {
    text(out, "tool_use_id", input.tool_use_id, 512);
    if (typeof input.sandbox === "boolean") out.sandbox = input.sandbox;
    return out;
  }
  text(out, "generation_id", input.generation_id, 256);
  text(out, "model", input.model, 128);
  text(out, "model_id", input.model_id, 128);
  if (hook === "afterAgentThought") {
    value = modelParams(input.model_params);
    if (value) out.model_params = value;
    return out;
  }
  text(out, "cursor_version", input.cursor_version, 64);
  text(out, "composer_mode", input.composer_mode, 32);
  if (POLICY.toolDetails && Array.isArray(input.workspace_roots)) {
    value = input.workspace_roots[0];
    if (typeof value === "string" && value.length > 0 && value.length <= 2048 && unchanged(value)) out.workspace_root = value;
  }
  if (POLICY.email && typeof input.user_email === "string" && EMAIL.test(input.user_email)) out.user_email = input.user_email;
  if (hook === "beforeSubmitPrompt") {
    if (typeof input.prompt === "string") {
      out.prompt_length = input.prompt.length;
      if (POLICY.prompts) out.prompt = promptText(input.prompt);
    }
    if (Array.isArray(input.attachments)) out.attachment_count = input.attachments.length;
    return out;
  }
  if (hook === "stop") {
    text(out, "status", input.status, 64);
    if (isNumber(input.loop_count)) out.loop_count = input.loop_count;
    var counters = ["input_tokens", "output_tokens", "cache_read_tokens", "cache_write_tokens"];
    for (i = 0; i < counters.length; i++) {
      key = counters[i];
      value = input[key];
      if (isNumber(value) || (typeof value === "string" && value.length <= 32)) out[key] = value;
    }
    return out;
  }
  text(out, "tool_name", input.tool_name, 128);
  text(out, "tool_use_id", input.tool_use_id, 512);
  if (isNumber(input.duration)) out.duration = input.duration;
  if (input.tool_input !== undefined) out.tool_input_size_bytes = Buffer.byteLength(JSON.stringify(input.tool_input), "utf8");
  if (hook === "postToolUse") {
    out.result = toolResult(input.tool_output);
  } else {
    text(out, "failure_type", input.failure_type, 64);
    if (typeof input.is_interrupt === "boolean") out.is_interrupt = input.is_interrupt;
    if (typeof input.error_message === "string") out.error_bytes = Buffer.byteLength(input.error_message, "utf8");
  }
  value = toolInput(input.tool_name, input.tool_input);
  if (value) out.tool_input = value;
  return out;
}
function encode(id, hook, conversation, payload) {
  return Buffer.from(JSON.stringify({
    v: 1, id: id, t: captured, hook: hook, conversation_id: conversation, p: POLICY, payload: payload
  }) + "\n", "utf8");
}
// The line for one event, inside the line bound, or null. Only prompt text can
// take a line past it (a character is up to six bytes of JSON), so the prompt is
// cut to the longest beginning that fits; tool arguments are never cut.
function fit(id, hook, conversation, payload) {
  var line = encode(id, hook, conversation, payload);
  if (line.length <= LIMITS.lineBytes) return line;
  var prompt = payload.prompt, low = 0, high, middle;
  delete payload.prompt;
  delete payload.tool_input;
  line = encode(id, hook, conversation, payload);
  if (line.length > LIMITS.lineBytes) return null;
  if (typeof prompt !== "string") return line;
  high = prompt.length;
  while (low < high) {
    middle = Math.ceil((low + high) / 2);
    payload.prompt = prompt.slice(0, middle);
    if (encode(id, hook, conversation, payload).length <= LIMITS.lineBytes) low = middle; else high = middle - 1;
  }
  if (low === 0) {
    delete payload.prompt;
    return line;
  }
  payload.prompt = whole(prompt.slice(0, low));
  return encode(id, hook, conversation, payload);
}
// Size of one file, or 0 when it is not a regular file that can be looked at.
function fileBytes(file) {
  try {
    var stat = fs.lstatSync(file);
    return stat.isFile() ? stat.size : 0;
  } catch (error) { return 0; }
}
// Bytes in the segments of earlier buckets, which no hook appends to any more.
// The sum is kept in a small file so that an event does not look at every
// segment. It is used only for the bucket and the number of such segments it
// was written for: a new bucket, or a segment the collector has removed,
// counts again. A missing, torn or foreign file counts again too.
function settledBytes(spool, names, own, bucket) {
  var file = STATE + "/spool-size", c = fs.constants, guard = (c.O_NOFOLLOW || 0) | (c.O_NONBLOCK || 0);
  var count = 0, total = 0, i, fd, key, text;
  for (i = 0; i < names.length; i++) if (!own.test(names[i])) count++;
  key = bucket + " " + count + " ";
  try {
    fd = fs.openSync(file, c.O_RDONLY | guard);
    try {
      var buffer = Buffer.alloc(64);
      text = fs.fstatSync(fd).isFile() ? buffer.toString("latin1", 0, fs.readSync(fd, buffer, 0, 64, 0)) : "";
    } finally { fs.closeSync(fd); }
    if (text.indexOf(key) === 0 && /^\d{1,15}\n$/.test(text.slice(key.length))) return +text.slice(key.length);
  } catch (error) {}
  for (i = 0; i < names.length; i++) if (!own.test(names[i])) total += fileBytes(spool + "/" + names[i]);
  try {
    fd = fs.openSync(file, c.O_WRONLY | c.O_CREAT | c.O_TRUNC | guard, 384);
    try {
      if (fs.fstatSync(fd).isFile()) fs.writeSync(fd, key + total + "\n");
    } finally { fs.closeSync(fd); }
  } catch (error) {}
  return total;
}
// One O_APPEND write of one whole line: concurrent hook processes never
// interleave. The spool is bounded in bytes and in files; past either bound the
// record is dropped, never queued. A bucket whose segment is full continues in
// "seg-<bucket>-<n>.jsonl", so a burst is not dropped while the spool has room.
function append(line) {
  var spool = STATE + "/spool";
  var bucket = Math.floor(Date.now() / LIMITS.segmentMs);
  var own = new RegExp("^seg-" + bucket + "(?:-([1-9]\\d{0,3}))?[.]jsonl$");
  var names = fs.readdirSync(spool);
  var mine = [], part = 0, i, match, name;
  if (names.length > LIMITS.segments) return false;
  for (i = 0; i < names.length; i++) {
    match = own.exec(names[i]);
    if (!match) continue;
    mine.push(names[i]);
    if (match[1] && +match[1] > part) part = +match[1];
  }
  // With no more files than this the byte bound cannot have been reached, and
  // no file is looked at. Beyond it the bucket's own segments are, and the rest
  // comes from the kept sum.
  if (names.length * LIMITS.segmentBytes > LIMITS.spoolBytes) {
    var total = settledBytes(spool, names, own, bucket);
    for (i = 0; i < mine.length; i++) total += fileBytes(spool + "/" + mine[i]);
    if (total + line.length > LIMITS.spoolBytes) return false;
  }
  // The bucket's newest segment, then the next number when that one is full.
  for (var tries = 0; tries < 2; tries++, part++) {
    if (part > 9999) return false;
    name = "seg-" + bucket + (part ? "-" + part : "") + ".jsonl";
    if (names.length >= LIMITS.segments && names.indexOf(name) < 0) return false;
    var fd = fs.openSync(spool + "/" + name, appendFlags(), 384);
    try {
      var stat = fs.fstatSync(fd);
      if (!stat.isFile()) return false;
      if (stat.size + line.length > LIMITS.segmentBytes) continue;
      var written = fs.writeSync(fd, line, 0, line.length);
      if (written === line.length) return true;
      // A short write (full disk) left a partial line; end it so the next record stays intact.
      if (written > 0) {
        try { fs.writeSync(fd, "\n"); } catch (error) {}
      }
      return false;
    } finally { fs.closeSync(fd); }
  }
  return false;
}
// Returns false when the event should have produced a line and did not.
function record(source) {
  var input = JSON.parse(source);
  if (!isObject(input)) return false;
  var hook = input.hook_event_name;
  if (HOOKS.indexOf(hook) < 0) return true;
  var conversation = input.conversation_id;
  if (typeof conversation !== "string" || !IDENTITY.test(conversation)) return false;
  var id = crypto.randomBytes(16).toString("hex");
  var line = fit(id, hook, conversation, build(hook, input));
  return line !== null && append(line);
}
// Runs at end of input, or at the deadline with whatever has arrived.
function settle() {
  if (settled) return;
  settled = true;
  var kept = false;
  try {
    kept = !over && record(Buffer.concat(chunks).toString("utf8"));
  } catch (error) {}
  if (kept) quit(); else fail();
}

try {
  process.removeAllListeners("warning");
  process.on("uncaughtException", fail);
  fs = require("fs");
  crypto = require("crypto");
  captured = stamp();
  // Not unref'd: this is the deadline. The read below is asynchronous so that
  // it can fire while stdin is still open.
  setTimeout(settle, LIMITS.deadlineMs);
  process.stdin.on("error", fail);
  process.stdin.on("data", function (chunk) {
    if (over) return;
    size += chunk.length;
    if (size > LIMITS.stdinBytes) {
      over = true;
      chunks = [];
    } else chunks.push(chunk);
  });
  process.stdin.on("end", settle);
} catch (error) {
  fail();
}
`;
}

/** A single-quoted shell word. Line breaks and NUL cannot be carried by a launcher. */
function shellWord(value: string, label: string): string {
  if (/[\0\r\n]/.test(value)) throw new Error(`${label} contains a line break or NUL and cannot be written to a launcher`);
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

/** `hook.sh`, the command registered in hooks.json. Cursor blocks the user's
 *  action when a hook exits 2, and a POSIX shell itself exits 2 on a failed
 *  redirection of a special built-in, so the EXIT trap pins the status to 0 and
 *  the stale-interpreter bookkeeping runs in subshells. The interpreter is tried
 *  as recorded, then as `command -v node` named it at install, then from PATH. */
export function cursorHookLauncher(opts: { stateDir: string; program: string; node: CursorNode }): string {
  return [
    "#!/bin/sh",
    `# ${CURSOR_FILE_MARKER}`,
    "# Generated by codetelemetry-connect. Every path exits 0 and prints nothing.",
    "trap 'exit 0' EXIT",
    "exec >/dev/null 2>&1",
    `S=${shellWord(opts.stateDir, "state directory")}`,
    `N=${shellWord(opts.node.execPath, "Node.js path")}`,
    `if [ ! -f "$N" ] || [ ! -x "$N" ]; then N=${shellWord(opts.node.commandPath ?? "", "Node.js command path")}; fi`,
    'if [ ! -f "$N" ] || [ ! -x "$N" ]; then',
    "  N=$(command -v node) || exit 0",
    '  case "$N" in /*) ;; *) exit 0 ;; esac',
    "  P=",
    '  if [ -f "$S/node-path" ]; then read -r P < "$S/node-path"; fi',
    `  if [ "$P" != "$N" ]; then ( umask 077; printf '%s\\n' "$N" > "$S/node-path" ); fi`,
    '  if [ ! -e "$S/node-stale" ]; then ( umask 077; : > "$S/node-stale" ); fi',
    "fi",
    `NODE_OPTIONS= "$N" ${shellWord(opts.program, "hook program path")}`,
    "exit 0",
    "",
  ].join("\n");
}

/** Every variable Node.js reads to choose a proxy. The collector launcher clears
 *  them all before it exports the recorded settings: Node.js prefers the
 *  lower-case spelling, and an https request falls back to the http proxy, so
 *  an inherited variable would otherwise override what `login` recorded. */
const PROXY_VARIABLES = ["HTTPS_PROXY", "https_proxy", "HTTP_PROXY", "http_proxy", "NO_PROXY", "no_proxy", "NODE_USE_ENV_PROXY"];

/** A collector that exits unsuccessfully sooner than this after it started
 *  failed at start: its state, its settings or its lock refused it. */
export const CURSOR_EARLY_EXIT_SECONDS = 10;

/** `collector.sh`, what the service manager starts. The unit never names a
 *  Node.js binary: this tries the recorded pair, then the path the hook last
 *  found, and accepts only a new enough interpreter. With none it marks the
 *  state stale and exits 1 after a wait, so the manager retries slowly. The
 *  collector's proxy settings are exactly the recorded ones.
 *
 *  The collector runs as a child, not in place of the shell, so that a failed
 *  start can be slowed down here whatever the service manager's own restart
 *  delay is: a start that fails within CURSOR_EARLY_EXIT_SECONDS is passed on
 *  only after `failureSeconds`. A stop request is forwarded to the collector,
 *  and its exit is then passed on at once. */
export function cursorCollectorLauncher(opts: {
  stateDir: string; node: CursorNode; entry: string; configPath: string; network?: CursorNetwork; retrySeconds?: number; failureSeconds?: number;
}): string {
  const retrySeconds = opts.retrySeconds ?? 300, failureSeconds = opts.failureSeconds ?? 60;
  if ([retrySeconds, failureSeconds].some(seconds => !Number.isSafeInteger(seconds) || seconds < 1 || seconds > 3600)) throw new Error("invalid Cursor collector retry wait");
  const network = opts.network ?? {};
  const exported: Array<[string, string | undefined]> = [
    ["HTTPS_PROXY", network.httpsProxy], ["NO_PROXY", network.noProxy], ["NODE_EXTRA_CA_CERTS", network.extraCaCerts],
  ];
  return [
    "#!/bin/sh",
    `# ${CURSOR_FILE_MARKER}`,
    "# Generated by codetelemetry-connect.",
    `trap 'r=$?; if [ "$r" -eq 2 ]; then r=1; fi; exit "$r"' EXIT`,
    `S=${shellWord(opts.stateDir, "state directory")}`,
    `unset ${PROXY_VARIABLES.join(" ")}`,
    ...exported.flatMap(([name, value]) => value ? [`export ${name}=${shellWord(value, name)}`] : []),
    ...(network.httpsProxy ? ["export NODE_USE_ENV_PROXY=1"] : []),
    "P=",
    'if [ -f "$S/node-path" ]; then read -r P < "$S/node-path"; fi',
    `for N in ${shellWord(opts.node.execPath, "Node.js path")} ${shellWord(opts.node.commandPath ?? "", "Node.js command path")} "$P"; do`,
    '  case "$N" in /*) ;; *) continue ;; esac',
    '  if [ -f "$N" ] && [ -x "$N" ] && "$N" -e \'process.exit(+process.versions.node.split(".")[0]>=' + CURSOR_NODE_MAJOR + "?0:1)' >/dev/null 2>&1; then",
    "    T=$(date +%s 2>/dev/null) || T=0",
    "    K=0",
    `    "$N" ${shellWord(opts.entry, "collector entry")} cursor collect --settings ${shellWord(opts.configPath, "config path")} &`,
    "    C=$!",
    `    trap 'K=1; kill -TERM "$C" 2>/dev/null' TERM INT HUP`,
    '    wait "$C"; R=$?',
    "    # A trapped signal ends the wait early; the collector's own status is still owed.",
    '    while kill -0 "$C" 2>/dev/null; do wait "$C"; R=$?; done',
    "    trap - TERM INT HUP",
    `    if [ "$R" -ne 0 ] && [ "$K" -eq 0 ] && [ $(( $(date +%s 2>/dev/null || echo 0) - T )) -lt ${CURSOR_EARLY_EXIT_SECONDS} ]; then sleep ${failureSeconds}; fi`,
    '    exit "$R"',
    "  fi",
    "done",
    '( umask 077; : > "$S/node-stale" ) 2>/dev/null',
    `sleep ${retrySeconds}`,
    "exit 1",
    "",
  ].join("\n");
}

function ownedDirectory(directory: string): void {
  fs.mkdirSync(directory, { recursive: true, mode: 0o700 });
  const stat = fs.lstatSync(directory);
  if (stat.isSymbolicLink() || !stat.isDirectory()) throw new Error(`${directory} must be a directory, not a link`);
  if ((stat.mode & 0o777) !== 0o700) fs.chmodSync(directory, 0o700);
}

/** Write an owned executable only when its bytes or mode differ. */
function writeOwned(file: string, body: string): boolean {
  let stat: fs.Stats | null = null;
  try {
    stat = fs.lstatSync(file);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
  }
  if (stat?.isDirectory()) throw new Error(`refusing to replace ${file}: it is a directory`);
  if (stat?.isFile() && (stat.mode & 0o777) === 0o700 && stat.size === Buffer.byteLength(body) &&
    fs.readFileSync(file, "utf8") === body) return false;
  writeCursorFileAtomic(file, body, 0o700);
  return true;
}

export type CursorHookFilesOptions = {
  shareDir: string;
  stateDir: string;
  content: ContentPolicy;
  identity: CursorIdentity;
  node: CursorNode;
};

/** Install `hook.cjs` and `hook.sh` and the directories the hook appends to.
 *  Called on every login, so it also clears the stale-interpreter markers: the
 *  launchers now hold the current paths. Returns the command for hooks.json. */
export function installCursorHookFiles(opts: CursorHookFilesOptions): { command: string; written: string[] } {
  const files = cursorShareFiles(opts.shareDir), state = cursorStateFiles(opts.stateDir);
  if (!isSafeCursorPath(files.hook)) {
    throw new Error(`Cursor runs hook commands through a shell without quoting, so the hook cannot be installed under ${opts.shareDir}: the path may only contain letters, digits and . _ / @ + - (no spaces).`);
  }
  // Refuse values a launcher cannot carry before anything is written.
  const program = cursorHookProgram(opts);
  const launcher = cursorHookLauncher({ stateDir: opts.stateDir, program: files.hookProgram, node: opts.node });
  ownedDirectory(opts.shareDir);
  ownedDirectory(opts.stateDir);
  ownedDirectory(state.spool);
  const written: string[] = [];
  if (writeOwned(files.hookProgram, program)) written.push(files.hookProgram);
  if (writeOwned(files.hook, launcher)) written.push(files.hook);
  fs.rmSync(state.nodePath, { force: true });
  fs.rmSync(state.nodeStale, { force: true });
  return { command: files.hook, written };
}

/** Install `collector.sh` once the service runtime's entry is known. */
export function installCursorCollectorLauncher(opts: {
  shareDir: string; stateDir: string; node: CursorNode; entry: string; configPath: string; network?: CursorNetwork; retrySeconds?: number; failureSeconds?: number;
}): { path: string; written: boolean } {
  const file = cursorShareFiles(opts.shareDir).collectorLauncher;
  const body = cursorCollectorLauncher(opts);
  ownedDirectory(opts.shareDir);
  return { path: file, written: writeOwned(file, body) };
}

/** Remove the hook pair so any entry still naming it becomes inert; with
 *  `collector`, the collector launcher too. Returns what was removed. */
export function removeCursorHookFiles(shareDir: string, opts: { collector?: boolean } = {}): string[] {
  const files = cursorShareFiles(shareDir), removed: string[] = [];
  for (const file of [files.hook, files.hookProgram, ...(opts.collector ? [files.collectorLauncher] : [])]) {
    try {
      fs.unlinkSync(file);
      removed.push(file);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    }
  }
  return removed;
}
